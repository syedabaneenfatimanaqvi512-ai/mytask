# Initialize Output Widgets
console_output = widgets.Output()
history_output = widgets.Output()

# Styled Controls using matching colors
input_slider = widgets.IntSlider(
    value=50,
    min=1,
    max=100,
    step=1,
    description='Adjust Guess:',
    continuous_update=False,
    style={'description_width': 'initial', 'handle_color': '#38bdf8'},
    layout=widgets.Layout(width='95%', margin='10px 0')
)

submit_btn = widgets.Button(
    description='SUBMIT GUESS',
    button_style='info',
    tooltip='Test this number!',
    icon='gamepad',
    layout=widgets.Layout(width='160px', height='42px')
)

restart_btn = widgets.Button(
    description='RESET ARCADE',
    button_style='warning',
    tooltip='Generate new target number',
    icon='refresh',
    layout=widgets.Layout(width='160px', height='42px')
)

# Horizontal layout of buttons
control_buttons = widgets.HBox(
    [submit_btn, restart_btn],
    layout=widgets.Layout(justify_content='center', gap='15px', margin='10px 0 0 0')
)

# Render dashboard update
def update_console(feedback=""):
    with console_output:
        console_output.clear_output()
        html_dashboard = f"""
        {dashboard_css}
        <div class="game-console">
            <div class="brand-title">🎮 GUESSING CONSOLE</div>
            <div class="brand-tagline">Can you crack the secret code?</div>

            <div class="hud-display">
                <div class="hud-badge">Attempts: <span>{total_attempts}</span></div>
                <div class="hud-badge">Status: <span>{'Playing' if submit_btn.disabled is False else 'Ended'}</span></div>
            </div>

            {feedback if feedback else '<div style="padding: 15px; color: #64748b; font-size: 14px;">Move the slider and click Submit Guess!</div>'}
        </div>
        """
        display(HTML(html_dashboard))

# Render interactive historical log
def update_history_log():
    with history_output:
        history_output.clear_output()
        if not guess_history:
            return

        rows_html = ""
        for index, (guess, feedback) in enumerate(reversed(guess_history)):
            css_class = "log-low" if "Low" in feedback else "log-high" if "High" in feedback else "log-win"
            rows_html += f"""
            <div class="log-row {css_class}">
                <span>Guess #{len(guess_history) - index}: <b>{guess}</b></span>
                <span>{feedback}</span>
            </div>
            """

        display(HTML(f"""
        <div class="log-container">
            <div class="log-header">🎮 Historical Attempts</div>
            {rows_html}
        </div>
        """))

# Button interaction callbacks
def handle_submit(b):
    global total_attempts, target_number
    val = input_slider.value
    total_attempts += 1

    if val < target_number:
        txt = "Too Low 📉"
        box = f'<div class="alert-box alert-low">📉 <b>{val}</b> is too low! Try a higher number.</div>'
        guess_history.append((val, txt))
    elif val > target_number:
        txt = "Too High 📈"
        box = f'<div class="alert-box alert-high">📈 <b>{val}</b> is too high! Try a lower number.</div>'
        guess_history.append((val, txt))
    else:
        txt = "Correct 🎉"
        box = f"""
        <div class="alert-box alert-win">
            🎉 <b>Boom! Perfect Match!</b><br>
            The secret target was <b>{target_number}</b>.<br>
            🏆 Solved in <b>{total_attempts}</b> attempts!
        </div>
        """
        guess_history.append((val, txt))
        submit_btn.disabled = True
        input_slider.disabled = True

    update_console(box)
    update_history_log()

def handle_reset(b):
    global target_number, total_attempts, guess_history
    target_number = random.randint(1, 100)
    total_attempts = 0
    guess_history = []

    submit_btn.disabled = False
    input_slider.disabled = False
    input_slider.value = 50

    update_console()
    update_history_log()

# Bind click events
submit_btn.on_click(handle_submit)
restart_btn.on_click(handle_reset)

# First render loop
update_console()

# Clean layout wrapper
app_layout = widgets.VBox([
    console_output,
    widgets.VBox([input_slider, control_buttons], layout=widgets.Layout(align_items='center', margin='10px 0')),
    history_output
], layout=widgets.Layout(align_items='center'))

display(app_layout)